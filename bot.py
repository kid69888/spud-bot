# ── /listkeys ─────────────────────────────────────────────────
@tree.command(name="listkeys", description="List all active keys")
async def listkeys(interaction: discord.Interaction):
    role_ids = [r.id for r in interaction.user.roles]
    if ADMIN_ROLE not in role_ids:
        await interaction.response.send_message(
            "❌ No permission.", ephemeral=True); return
    async with aiosqlite.connect(DB_PATH) as db:
        async with db.execute(
            "SELECT key,tier,redeemed_by,expires_at,active FROM licenses"
            " ORDER BY created_at DESC LIMIT 50") as cur:
            rows = await cur.fetchall()
    if not rows:
        await interaction.response.send_message(
            "No keys found.", ephemeral=True); return
    lines = []
    for k, tier, red, exp, active in rows:
        status = "✅" if active else "❌"
        redeemed = f"redeemed:{red[:18]}" if red else "unredeemed"
        lines.append(f"{status} `{k}` [{tier}] {redeemed}")
    # Discord embed has 4096 char limit — chunk if needed
    chunks = [""]
    for line in lines:
        if len(chunks[-1]) + len(line) > 3900:
            chunks.append("")
        chunks[-1] += line + "\n"
    embed = discord.Embed(title="🥔 License Keys", color=0x4169E1)
    embed.description = chunks[0]
    await interaction.response.send_message(embed=embed, ephemeral=True)

