TOKEN        = os.getenv("DISCORD_TOKEN", "YOUR_BOT_TOKEN_HERE")
ADMIN_ROLE   = int(os.getenv("ADMIN_ROLE_ID", "0"))   # role allowed to /generate
CHANNEL_ID   = int(os.getenv("BOT_CHANNEL_ID", "0"))  # channel bot responds in
DB_PATH      = "licenses.db"

# ── tier durations ────────────────────────────────────────────
TIERS = {
    "3day":     3,
    "2week":    14,
    "1month":   30,
    "6month":   180,
    "1year":    365,
    "lifetime": -1   # -1 = never expires
}

TIER_LABELS = {
    "3day":     "3 Days",
    "2week":    "2 Weeks",
    "1month":   "1 Month",
    "6month":   "6 Months",
    "1year":    "1 Year",
    "lifetime": "Lifetime"
}

# ── key generator ─────────────────────────────────────────────
def make_key(tier: str) -> str:
    # Format: SPUD-TIER-XXXX-XXXX-XXXX
    # e.g.  SPUD-3DAY-A3F2-19BC-77EE
    charset = string.ascii_uppercase + string.digits
    seg = lambda: "".join(secrets.choice(charset) for _ in range(4))
    prefix = tier.upper().replace("MONTH","MO").replace("WEEK","WK").replace("YEAR","YR").replace("LIFETIME","LT")
    return f"SPUD-{prefix}-{seg()}-{seg()}-{seg()}"

# ── DB setup ──────────────────────────────────────────────────
async def init_db():
    async with aiosqlite.connect(DB_PATH) as db:
        await db.execute("""
            CREATE TABLE IF NOT EXISTS licenses (
                key         TEXT PRIMARY KEY,
                tier        TEXT NOT NULL,
                created_by  TEXT NOT NULL,
                created_at  TEXT NOT NULL,
                expires_at  TEXT,
                redeemed_by TEXT,
                redeemed_at TEXT,
                hwid        TEXT,
                active      INTEGER DEFAULT 1
            )
        """)
        await db.commit()

# ── bot setup ─────────────────────────────────────────────────
intents = discord.Intents.default()
intents.message_content = True
bot = commands.Bot(command_prefix="!", intents=intents)
tree = bot.tree

@bot.event
async def on_ready():
    await init_db()
    await tree.sync()
    print(f"[SPUD] Bot live as {bot.user}")

# ── /generate ────────────────────────────────────────────────
@tree.command(name="generate", description="Generate a license key")
@app_commands.describe(tier="Key tier", amount="How many keys (default 1, max 10)")
@app_commands.choices(tier=[
    app_commands.Choice(name="3 Days",    value="3day"),
    app_commands.Choice(name="2 Weeks",   value="2week"),
    app_commands.Choice(name="1 Month",   value="1month"),
    app_commands.Choice(name="6 Months",  value="6month"),
    app_commands.Choice(name="1 Year",    value="1year"),
    app_commands.Choice(name="Lifetime",  value="lifetime"),
])
async def generate(interaction: discord.Interaction,
                   tier: str, amount: int = 1):
    # Check admin role
    role_ids = [r.id for r in interaction.user.roles]
    if ADMIN_ROLE not in role_ids:
        await interaction.response.send_message(
            "❌ No permission.", ephemeral=True)
        return

    amount = max(1, min(amount, 10))
    now    = datetime.datetime.utcnow().isoformat()
    days   = TIERS[tier]
    exp    = None if days == -1 else (
        datetime.datetime.utcnow() +
        datetime.timedelta(days=days)).isoformat()

    keys = []
    async with aiosqlite.connect(DB_PATH) as db:
        for _ in range(amount):
            k = make_key(tier)
            await db.execute(
                "INSERT INTO licenses VALUES (?,?,?,?,?,NULL,NULL,NULL,1)",
                (k, tier, str(interaction.user), now, exp))
            keys.append(k)
        await db.commit()

    label = TIER_LABELS[tier]
    exp_str = "Never" if exp is None else exp[:10]
    lines = "\n".join(f"`{k}`" for k in keys)

    embed = discord.Embed(
        title=f"🥔 {amount}x {label} Key{'s' if amount>1 else ''} Generated",
        color=0xFFC83D)
    embed.add_field(name="Keys", value=lines, inline=False)
    embed.add_field(name="Tier",    value=label,   inline=True)
    embed.add_field(name="Expires", value=exp_str, inline=True)
    embed.set_footer(text=f"Generated by {interaction.user}")
    await interaction.response.send_message(embed=embed, ephemeral=True)

# ── /redeem ───────────────────────────────────────────────────
@tree.command(name="redeem", description="Redeem your license key")
@app_commands.describe(key="Your SPUD-XXXX key")
async def redeem(interaction: discord.Interaction, key: str):
    key = key.strip().upper()
    now = datetime.datetime.utcnow().isoformat()

    async with aiosqlite.connect(DB_PATH) as db:
        async with db.execute(
            "SELECT * FROM licenses WHERE key=?", (key,)) as cur:
            row = await cur.fetchone()

        if not row:
            await interaction.response.send_message(
                "❌ Invalid key.", ephemeral=True); return

        cols = ["key","tier","created_by","created_at","expires_at",
                "redeemed_by","redeemed_at","hwid","active"]
        lic = dict(zip(cols, row))

        if not lic["active"]:
            await interaction.response.send_message(
                "❌ Key is revoked.", ephemeral=True); return
        if lic["redeemed_by"]:
            await interaction.response.send_message(
                "❌ Key already redeemed.", ephemeral=True); return
        if lic["expires_at"]:
            exp = datetime.datetime.fromisoformat(lic["expires_at"])
            if datetime.datetime.utcnow() > exp:
                await interaction.response.send_message(
                    "❌ Key expired.", ephemeral=True); return

        await db.execute(
            "UPDATE licenses SET redeemed_by=?, redeemed_at=? WHERE key=?",
            (str(interaction.user.id), now, key))
        await db.commit()

    label   = TIER_LABELS[lic["tier"]]
    exp_str = "Never" if not lic["expires_at"] else lic["expires_at"][:10]

    embed = discord.Embed(
        title="🥔 Key Redeemed!", color=0x32CD32)
    embed.add_field(name="Key",     value=f"`{key}`", inline=False)
    embed.add_field(name="Tier",    value=label,      inline=True)
    embed.add_field(name="Expires", value=exp_str,    inline=True)
    embed.set_footer(text="Use this key in Potato Spoofer to unlock.")
    await interaction.response.send_message(embed=embed, ephemeral=True)

